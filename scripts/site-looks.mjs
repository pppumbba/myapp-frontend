// Builds the website looks from the Hallmark theme catalogue (~/.claude/skills/hallmark):
//   src/pages/sites/looks.css   one token block per theme, [data-theme="<slug>"]
//   src/pages/sites/looks.ts    name, genre, material, font link and dark flag per theme
//   ../../myapp-backend/app/Support/SiteLooks.php   the slugs a site may pick
// Run again after updating Hallmark: node scripts/site-looks.mjs [hallmark-dir]
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const hallmark = process.argv[2] ?? join(homedir(), '.claude', 'skills', 'hallmark');
const { themes } = JSON.parse(readFileSync(join(hallmark, 'references', 'themes', 'index.json'), 'utf8'));
const work = mkdtempSync(join(tmpdir(), 'site-looks-'));

const blocks = new Map();
for (const theme of themes) {
  const dir = join(work, theme.slug);
  execFileSync(process.execPath, [join(hallmark, 'scripts', 'theme.mjs'), 'scaffold', theme.slug, '--dir', dir], { stdio: 'ignore' });
  const css = readFileSync(join(dir, 'tokens.css'), 'utf8');
  const body = css.slice(css.indexOf('{') + 1, css.lastIndexOf('}'));
  // Textures point at files the catalogue doesn't ship with the tokens.
  const lines = body.split('\n').map((l) => l.trim()).filter((l) => l && !l.includes('url('));
  blocks.set(theme.slug, lines);
}
rmSync(work, { recursive: true, force: true });

// The scale every theme shares goes on .hm-site once; each theme block keeps what is its own.
const all = [...blocks.values()];
const shared = all[0].filter((line) => all.every((b) => b.includes(line)) && !line.startsWith('color-scheme'));

const declared = (lines, name) => lines.some((l) => new RegExp(`(^|[;\\s])${name}:`).test(l));
let css = `/* Generated by scripts/site-looks.mjs from the Hallmark theme catalogue (${themes.length} themes). Don't edit by hand. */\n`;
css += `.hm-site {\n  ${shared.join('\n  ')}\n}\n`;
const looks = [];
for (const theme of themes) {
  const lines = blocks.get(theme.slug).filter((l) => !shared.includes(l));
  const all = blocks.get(theme.slug);
  const dark = theme.paper.L < 50;
  const heavy = declared(all, '--rule-bar');
  const defaults = [
    '--rule-bar: 2px;',
    '--color-accent-2: var(--color-accent);',
    '--color-rule-2: var(--color-ink-2);',
    // Themes with a heavy rule frame their boxes in ink; the rest in a hairline.
    `--frame: ${heavy ? 'var(--rule-bar) solid var(--color-ink)' : 'var(--rule-hair) solid var(--color-rule)'};`,
    `--radius-control: ${declared(all, '--radius-input') ? 'var(--radius-input)' : 'var(--radius-pill)'};`,
  ];
  css += `[data-theme="${theme.slug}"] {\n  ${[...defaults, ...lines].join('\n  ')}\n}\n`;
  const md = readFileSync(join(hallmark, 'references', 'themes', `${theme.slug}.md`), 'utf8');
  const font = /<link href="(https:\/\/[^"]+)" rel="stylesheet">/.exec(md)?.[1] ?? null;
  looks.push({ slug: theme.slug, name: theme.name, genre: theme.genre, material: theme.material, font, dark });
}

const out = join(here, '..', 'src', 'pages', 'sites');
writeFileSync(join(out, 'looks.css'), css);
writeFileSync(
  join(out, 'looks.ts'),
  `// Generated by scripts/site-looks.mjs from the Hallmark theme catalogue. Don't edit by hand.\n\n` +
    `export interface SiteLook {\n  slug: string;\n  name: string;\n  genre: string;\n  /** What the theme is made of, in the catalogue's words. */\n  material: string;\n  /** Its faces, loaded while a site wearing it is open. */\n  font: string | null;\n  dark: boolean;\n}\n\n` +
    `export const DEFAULT_LOOK = 'wayfind';\n\n` +
    `export const SITE_LOOKS: SiteLook[] = ${JSON.stringify(looks, null, 2)};\n\n` +
    `export const siteLook = (slug: string | null | undefined) => SITE_LOOKS.find((l) => l.slug === slug) ?? SITE_LOOKS.find((l) => l.slug === DEFAULT_LOOK)!;\n`,
);
writeFileSync(
  join(here, '..', '..', '..', 'myapp-backend', 'app', 'Support', 'SiteLooks.php'),
  `<?php\n\nnamespace App\\Support;\n\n/** The looks a website may wear: Hallmark's theme catalogue. Generated by the frontend's scripts/site-looks.mjs. */\nclass SiteLooks\n{\n    public const DEFAULT = 'wayfind';\n\n    public const SLUGS = [\n${looks.map((l) => `        '${l.slug}',`).join('\n')}\n    ];\n}\n`,
);
console.log(`${looks.length} looks, ${shared.length} shared lines; ${looks.filter((l) => !l.font).length} without a font link`);
